import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const ROOT = path.resolve(__dirname, '../..');

export const DIRS = {
  projects: path.join(ROOT, 'public/images/projects'),
  awards: path.join(ROOT, 'public/images/awards'),
  blogs: path.join(ROOT, 'public/images/blogs'),
  leadership: path.join(ROOT, 'public/images/leadership'),
  reports: path.join(ROOT, 'public/reports'),
  uploads: path.join(ROOT, 'public/images/uploads')
};

for (const dir of Object.values(DIRS)) {
  if (!fs.existsSync(dir)) fs.mkdirSync(dir, { recursive: true });
}

/**
 * Normalizes a remote media filename to a clean local filename.
 */
export function cleanMediaFilename(rawUrl) {
  if (!rawUrl || typeof rawUrl !== 'string') return '';
  const cleanUrl = rawUrl.split('?')[0].split('#')[0];
  const basename = cleanUrl.split('/').pop() || '';
  return basename.replace(/[^a-zA-Z0-9._-]/g, '_');
}

/**
 * Classifies a media URL into a specific asset category folder.
 */
export function classifyMediaCategory(url, parentKey = '', context = '') {
  const lowerUrl = (url || '').toLowerCase();
  const lowerKey = (parentKey || '').toLowerCase();
  const lowerCtx = (context || '').toLowerCase();

  if (lowerUrl.endsWith('.pdf') || lowerKey.includes('pdf') || lowerKey.includes('report') || lowerKey.includes('file')) {
    return 'reports';
  }
  if (lowerCtx.includes('project') || lowerKey.includes('project') || lowerUrl.includes('project')) {
    return 'projects';
  }
  if (lowerCtx.includes('award') || lowerKey.includes('award') || lowerUrl.includes('award')) {
    return 'awards';
  }
  if (lowerCtx.includes('blog') || lowerKey.includes('blog') || lowerUrl.includes('blog') || lowerKey.includes('excerpt')) {
    return 'blogs';
  }
  if (lowerCtx.includes('leader') || lowerKey.includes('leader') || lowerKey.includes('executive') || lowerKey.includes('coreteam')) {
    return 'leadership';
  }
  return 'uploads';
}

/**
 * Recursively crawls any JSON/JS data structure to discover all media URLs.
 * Automatically ignores thumbnail derivatives (small, medium, thumbnail) to prevent redundant downloads.
 */
export function crawlMediaUrls(data, currentKey = '', context = '', foundMap = new Map()) {
  if (!data) return foundMap;

  // Skip redundant thumbnail formats generated by Strapi
  if (currentKey === 'thumbnail' || currentKey === 'small' || currentKey === 'medium') {
    return foundMap;
  }

  if (typeof data === 'string') {
    const s = data.trim();
    const isUrl = s.startsWith('http://') || s.startsWith('https://') || s.startsWith('/uploads/');
    const hasMediaExt = /\.(png|jpe?g|webp|avif|svg|pdf)$/i.test(s.split('?')[0]);
    const isCdn = s.includes('r2.dev/') || s.includes('res.cloudinary.com/') || s.includes(':1337/uploads/');

    if (isUrl && (hasMediaExt || isCdn)) {
      if (!foundMap.has(s)) {
        const category = classifyMediaCategory(s, currentKey, context);
        const filename = cleanMediaFilename(s);
        if (filename) {
          foundMap.set(s, { url: s, category, filename, context });
        }
      }
    }
    return foundMap;
  }

  if (Array.isArray(data)) {
    for (let i = 0; i < data.length; i++) {
      crawlMediaUrls(data[i], `${currentKey}[${i}]`, context || currentKey, foundMap);
    }
    return foundMap;
  }

  if (typeof data === 'object') {
    const nextContext = data.title || data.name || data.slug || context || currentKey;
    for (const [k, v] of Object.entries(data)) {
      crawlMediaUrls(v, k, nextContext, foundMap);
    }
    return foundMap;
  }

  return foundMap;
}

/**
 * Downloads a single media asset safely with retry and integrity validation.
 */
export async function downloadMediaAsset(urlInfo, explicitTargetPath = null) {
  let url = '';
  let category = 'uploads';
  let filename = '';

  if (typeof urlInfo === 'string') {
    url = urlInfo;
    filename = explicitTargetPath ? path.basename(explicitTargetPath) : cleanMediaFilename(url);
    category = classifyMediaCategory(url);
  } else if (urlInfo && typeof urlInfo === 'object') {
    url = urlInfo.url;
    category = urlInfo.category || classifyMediaCategory(url);
    filename = urlInfo.filename || cleanMediaFilename(url);
  }
  if (!filename) return false;

  const targetDir = category === 'reports' ? DIRS.reports : (DIRS[category] || DIRS.uploads);
  const targetPath = explicitTargetPath || path.join(targetDir, filename);

  // Incremental: Check if this file already exists in ANY media directory to prevent duplicate downloads
  const allDirs = [DIRS.projects, DIRS.awards, DIRS.blogs, DIRS.leadership, DIRS.reports, DIRS.uploads];
  for (const dir of allDirs) {
    const candidatePath = path.join(dir, filename);
    if (fs.existsSync(candidatePath)) {
      try {
        const stat = fs.statSync(candidatePath);
        if (stat.size > 0) {
          // Also ensure dist has it if dist exists
          const distDir = path.join(ROOT, 'dist', path.relative(path.join(ROOT, 'public'), dir));
          if (fs.existsSync(path.join(ROOT, 'dist'))) {
            if (!fs.existsSync(distDir)) fs.mkdirSync(distDir, { recursive: true });
            const distTarget = path.join(distDir, filename);
            if (!fs.existsSync(distTarget)) {
              fs.copyFileSync(candidatePath, distTarget);
            }
          }
          return { status: 'already_cached', path: candidatePath };
        }
      } catch (e) {}
    }
  }

  // Handle local Strapi relative URL
  let fetchUrl = url;
  if (url.startsWith('/uploads/')) {
    fetchUrl = `http://localhost:1337${url}`;
  }

  try {
    const res = await fetch(fetchUrl, {
      signal: AbortSignal.timeout(6000),
      headers: { 'User-Agent': 'PislinfraMediaSync/2.0' }
    });
    if (res.ok) {
      const buf = Buffer.from(await res.arrayBuffer());
      if (buf.length > 0) {
        fs.writeFileSync(targetPath, buf);

        // Copy to dist if dist exists
        const distDir = path.join(ROOT, 'dist', path.relative(path.join(ROOT, 'public'), targetDir));
        if (fs.existsSync(path.join(ROOT, 'dist'))) {
          if (!fs.existsSync(distDir)) fs.mkdirSync(distDir, { recursive: true });
          fs.writeFileSync(path.join(distDir, filename), buf);
        }
        return { status: 'downloaded', path: targetPath, size: buf.length };
      }
    }
  } catch (e) {}

  return { status: 'failed', url };
}

/**
 * Synchronizes all discovered media from the master dataset.
 */
export async function syncAllDiscoveredMedia(masterData) {
  const mediaMap = crawlMediaUrls(masterData);
  const mediaList = Array.from(mediaMap.values());

  const stats = {
    totalFound: mediaList.length,
    newlyDownloaded: 0,
    alreadyCached: 0,
    failed: 0
  };

  // Process in concurrent batches of 10
  const BATCH_SIZE = 10;
  for (let i = 0; i < mediaList.length; i += BATCH_SIZE) {
    const batch = mediaList.slice(i, i + BATCH_SIZE);
    const results = await Promise.all(batch.map(item => downloadMediaAsset(item)));
    for (const r of results) {
      if (!r || r.status === 'failed') stats.failed++;
      else if (r.status === 'downloaded') stats.newlyDownloaded++;
      else if (r.status === 'already_cached') stats.alreadyCached++;
    }
  }

  // Update Sets in src/utils/imageUrl.js so newly discovered assets resolve to local paths
  updateImageUrlSets();

  return stats;
}

/**
 * Auto-registers all local files in src/utils/imageUrl.js
 */
export function updateImageUrlSets() {
  try {
    const imgUrlPath = path.join(ROOT, 'src/utils/imageUrl.js');
    if (!fs.existsSync(imgUrlPath)) return;

    let content = fs.readFileSync(imgUrlPath, 'utf8');

    const updateSet = (varName, dirPath) => {
      if (fs.existsSync(dirPath)) {
        const files = fs.readdirSync(dirPath).filter(f => !f.startsWith('.') && /\.(jpe?g|png|webp|avif|svg)$/i.test(f));
        files.sort();
        const regex = new RegExp(`const\\s+${varName}\\s*=\\s*new\\s+Set\\(\\[[\\s\\S]*?\\]\\);`);
        const replacement = `const ${varName} = new Set(${JSON.stringify(files)});`;
        content = content.replace(regex, replacement);
      }
    };

    updateSet('PROJECT_FILES', DIRS.projects);
    updateSet('AWARD_FILES', DIRS.awards);
    updateSet('BLOG_FILES', DIRS.blogs);
    updateSet('LEADERSHIP_FILES', DIRS.leadership);
    updateSet('UPLOAD_FILES', DIRS.uploads);

    fs.writeFileSync(imgUrlPath, content, 'utf8');
  } catch (e) {
    console.warn('⚠️ Could not update imageUrl.js Sets:', e.message);
  }
}

function resolveLocalMediaPath(filename) {
  try {
    if (fs.existsSync(path.join(DIRS.blogs, filename))) return `/images/blogs/${filename}`;
    if (fs.existsSync(path.join(DIRS.projects, filename))) return `/images/projects/${filename}`;
    if (fs.existsSync(path.join(DIRS.awards, filename))) return `/images/awards/${filename}`;
    if (fs.existsSync(path.join(DIRS.leadership, filename))) return `/images/leadership/${filename}`;
    if (fs.existsSync(path.join(DIRS.reports, filename))) return `/reports/${filename}`;
  } catch (e) {}
  return `/images/uploads/${filename}`;
}

/**
 * Deep-rewrites any localhost:1337, 127.0.0.1:1337, Cloudflare R2, or Render URLs in content to relative production paths.
 */
export function sanitizeLocalhostUrls(data) {
  if (!data) return data;
  if (typeof data === 'string') {
    let str = data;
    // 1. Rewrite localhost and 127.0.0.1 URLs
    str = str.replace(/https?:\/\/(?:localhost|127\.0\.0\.1):1337\/uploads\/([a-zA-Z0-9._-]+)/g, (match, fn) => {
      const clean = fn.replace(/[^a-zA-Z0-9._-]/g, '_');
      return resolveLocalMediaPath(clean);
    });

    // 2. Rewrite Cloudflare R2 URLs
    str = str.replace(/https?:\/\/[a-zA-Z0-9.-]*\.r2\.dev\/([a-zA-Z0-9._-]+)/g, (match, fn) => {
      const clean = fn.replace(/[^a-zA-Z0-9._-]/g, '_');
      return resolveLocalMediaPath(clean);
    });

    // 3. Rewrite onrender Strapi URLs
    str = str.replace(/https?:\/\/cms-pislinfra\.onrender\.com\/uploads\/([a-zA-Z0-9._-]+)/g, (match, fn) => {
      const clean = fn.replace(/[^a-zA-Z0-9._-]/g, '_');
      return resolveLocalMediaPath(clean);
    });

    return str;
  }
  if (Array.isArray(data)) return data.map(sanitizeLocalhostUrls);
  if (typeof data === 'object') {
    const clean = {};
    for (const [k, v] of Object.entries(data)) {
      clean[k] = sanitizeLocalhostUrls(v);
    }
    return clean;
  }
  return data;
}
